document.addEventListener('DOMContentLoaded', () => {
    // Determine initial language
    let currentLang = localStorage.getItem('selected-lang');
    if (!currentLang) {
        // Fallback to browser language, default to 'en'
        const browserLang = navigator.language || navigator.userLanguage;
        currentLang = browserLang.startsWith('fr') ? 'fr' : 'en';
    }

    function applyLanguage(lang, animate = false) {
        document.documentElement.lang = lang;

        // Update all elements with data-i18n
        document.querySelectorAll('[data-i18n]').forEach(element => {
            const key = element.getAttribute('data-i18n');
            if (translations[lang] && translations[lang][key] !== undefined) {
                const targetText = translations[lang][key];
                if (animate) {
                    animateTextChange(element, targetText);
                } else {
                    element.textContent = targetText;
                }
            }
        });

        // Update language switcher button text
        const langText = document.querySelector('.lang-text');
        if (langText) {
            langText.textContent = lang === 'en' ? 'FR' : 'EN';
        }

        // Store language preference
        localStorage.setItem('selected-lang', lang);
        currentLang = lang;
    }

    function animateTextChange(element, targetText) {
        // Cancel any existing animation on this element
        if (element.animationFrameId) {
            cancelAnimationFrame(element.animationFrameId);
        }

        const originalText = element.textContent;
        const deleteSpeed = 6; // ms per character to erase
        const typeSpeed = 25; // ms per character to type
        const deleteDuration = originalText.length * deleteSpeed;
        const typeDuration = targetText.length * typeSpeed;
        const totalDuration = deleteDuration + typeDuration;
        const start = performance.now();

        function update(time) {
            const elapsed = time - start;

            if (elapsed < deleteDuration) {
                // Phase 1: Deleting
                const progress = elapsed / deleteDuration;
                const remainingLength = Math.floor((1 - progress) * originalText.length);
                element.textContent = originalText.slice(0, remainingLength) + '▊';
                element.animationFrameId = requestAnimationFrame(update);
            } else if (elapsed < totalDuration) {
                // Phase 2: Typing
                const progress = (elapsed - deleteDuration) / typeDuration;
                const currentLength = Math.min(Math.floor(progress * targetText.length), targetText.length);
                element.textContent = targetText.slice(0, currentLength) + '▊';
                element.animationFrameId = requestAnimationFrame(update);
            } else {
                // Complete
                element.textContent = targetText;
                element.animationFrameId = null;
            }
        }

        element.animationFrameId = requestAnimationFrame(update);
    }

    // Initialize translations without animation on page load
    applyLanguage(currentLang, false);

    // Bind switcher button
    const langSwitchBtn = document.getElementById('lang-switch');
    if (langSwitchBtn) {
        langSwitchBtn.addEventListener('click', () => {
            const nextLang = currentLang === 'en' ? 'fr' : 'en';
            applyLanguage(nextLang, true);
        });
    }

    // Profile picture flip animation on click
    const pfpCard = document.querySelector('.profile-pic-card');
    if (pfpCard) {
        let isAnimating = false;
        pfpCard.addEventListener('click', () => {
            if (isAnimating) return;
            isAnimating = true;

            // Trigger the 3D flip rotation (180deg)
            pfpCard.classList.add('flipped');

            // Wait 2 seconds showing grace.png, then flip back
            setTimeout(() => {
                pfpCard.classList.remove('flipped');

                // Allow clicking again after return transition completes (600ms)
                setTimeout(() => {
                    isAnimating = false;
                }, 600);
            }, 2000);
        });
    }
});
